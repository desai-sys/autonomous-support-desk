"""
Entry point of an application generated by CloudOps (shipped as handler.py).

This file is platform code, the same in every generated app. The app's own code
is next to it:

    static/index.html   the page (served at /)
    api.py              def handle(method, path, query, body, store) -> (status, data)
    job.py              def run(store) -> anything (for scheduled jobs)

It only uses the Python standard library and boto3, which the Lambda runtime
provides.
"""

import base64
import importlib
import json
import mimetypes
import os
import traceback
from pathlib import Path

ROOT = Path(__file__).resolve().parent
STATIC = ROOT / "static"
_TEXT_TYPES = ("text/", "application/json", "application/javascript", "image/svg+xml")
_store = None


class Store:
    """
    Simple persistent storage: JSON values addressed by a group and a key, e.g.
    store.put("todos", "42", {"title": "Buy milk", "done": False}).
    Backed by the app's DynamoDB table; without one it keeps data in memory only.
    """

    def __init__(self, table=None):
        self._table = table
        self._memory = {}

    def put(self, group, key, value):
        """Save a JSON-serialisable value under (group, key). Returns the value."""
        if self._table is None:
            self._memory[(str(group), str(key))] = json.dumps(value)
        else:
            self._table.put_item(Item={"pk": str(group), "sk": str(key), "doc": json.dumps(value)})
        return value

    def get(self, group, key, default=None):
        """The value saved under (group, key), or default."""
        if self._table is None:
            doc = self._memory.get((str(group), str(key)))
        else:
            doc = (self._table.get_item(Key={"pk": str(group), "sk": str(key)}).get("Item") or {}).get("doc")
        return json.loads(doc) if doc is not None else default

    def list(self, group):
        """Every item in a group as [{"key": ..., "value": ...}], ordered by key."""
        if self._table is None:
            return [{"key": k, "value": json.loads(doc)}
                    for (g, k), doc in sorted(self._memory.items()) if g == str(group)]
        from boto3.dynamodb.conditions import Key
        items, kwargs = [], {"KeyConditionExpression": Key("pk").eq(str(group))}
        while True:
            page = self._table.query(**kwargs)
            items += [{"key": i["sk"], "value": json.loads(i["doc"])} for i in page.get("Items", [])]
            if not page.get("LastEvaluatedKey"):
                return items
            kwargs["ExclusiveStartKey"] = page["LastEvaluatedKey"]

    def delete(self, group, key):
        """Remove (group, key). Removing something that isn't there is not an error."""
        if self._table is None:
            self._memory.pop((str(group), str(key)), None)
        else:
            self._table.delete_item(Key={"pk": str(group), "sk": str(key)})


def _get_store():
    global _store
    if _store is None:
        name = os.environ.get("TABLE_NAME", "")
        table = None
        if name:
            import boto3
            table = boto3.resource("dynamodb").Table(name)
        _store = Store(table)
    return _store


def _response(status, body, content_type="application/json", binary=False, cache="no-store"):
    return {"statusCode": int(status), "isBase64Encoded": binary,
            "headers": {"Content-Type": content_type, "Cache-Control": cache,
                        "X-Content-Type-Options": "nosniff"},
            "body": body}


def _json(status, data):
    return _response(status, json.dumps(data, default=str), "application/json; charset=utf-8")


def _static(path):
    relative = "index.html" if path in ("", "/") else path.lstrip("/")
    target = (STATIC / relative).resolve()
    if STATIC.resolve() not in target.parents or not target.is_file():
        return _response(404, "Not found", "text/plain; charset=utf-8")
    content_type = mimetypes.guess_type(target.name)[0] or "application/octet-stream"
    data = target.read_bytes()
    if content_type.startswith(_TEXT_TYPES):
        return _response(200, data.decode("utf-8", "replace"), f"{content_type}; charset=utf-8", cache="max-age=60")
    return _response(200, base64.b64encode(data).decode(), content_type, binary=True, cache="max-age=60")


def _api(method, path, query, raw_body):
    try:
        api = importlib.import_module("api")
    except ModuleNotFoundError:
        return _json(404, {"error": "This app has no API."})
    body = raw_body
    if isinstance(raw_body, str) and raw_body.strip():
        try:
            body = json.loads(raw_body)
        except ValueError:
            body = raw_body
    try:
        result = api.handle(method, path, query, body, _get_store())
    except Exception as e:  # report the app's own errors as JSON instead of a blank 502
        traceback.print_exc()
        return _json(500, {"error": str(e), "type": type(e).__name__})
    status, data = 200, result
    if isinstance(result, tuple) and len(result) == 2 and isinstance(result[0], int):
        status, data = result
    return _json(status, data)


def handler(event, context):
    http = (event.get("requestContext") or {}).get("http") if isinstance(event, dict) else None
    if not http:                                   # scheduled run (EventBridge)
        result = importlib.import_module("job").run(_get_store())
        print(json.dumps({"job_result": result}, default=str))
        return {"status": "ok", "result": result if isinstance(result, (str, int, float, bool, type(None))) else str(result)}

    method = (http.get("method") or "GET").upper()
    path = event.get("rawPath") or "/"
    body = event.get("body")
    if body and event.get("isBase64Encoded"):
        body = base64.b64decode(body).decode("utf-8", "replace")
    if path == "/api" or path.startswith("/api/"):
        return _api(method, path, event.get("queryStringParameters") or {}, body)
    if method not in ("GET", "HEAD"):
        return _response(405, "Method not allowed", "text/plain; charset=utf-8")
    return _static(path)
