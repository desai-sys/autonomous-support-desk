"""
Blueprints: the shapes of application the builder can create.

Each blueprint is a CloudFormation template the platform owns and tests, plus
the list of files the model has to write for it. Generated stacks contain no
IAM resources: every function runs as one pre-created role
(``cloudops-generated-app``) that can only write logs and use DynamoDB tables
named ``cloudops-gen-*``. So generated code can never be granted more than
that, and deploying an app needs no permission to create roles.
"""

import re
from dataclasses import dataclass
from pathlib import Path
from typing import Dict, List

RESOURCE_PREFIX = "cloudops-gen-"
EXECUTION_ROLE_NAME = "cloudops-generated-app"
RUNTIME_SOURCE = (Path(__file__).parent / "runtime_handler.py").read_text(encoding="utf-8")
SCHEDULE_RE = re.compile(r"^(rate\(\d+ (minute|minutes|hour|hours|day|days)\)|cron\([^()]{9,100}\))$")
DEFAULT_SCHEDULE = "rate(1 day)"


@dataclass(frozen=True)
class Blueprint:
    name: str
    summary: str                 # shown to the planner model
    files: tuple                 # files the model writes, in the order they are written
    has_url: bool
    creates: str                 # shown to the operator


BLUEPRINTS: Dict[str, Blueprint] = {b.name: b for b in (
    Blueprint("static-site",
              "A single web page that runs entirely in the browser: games, calculators, landing pages, "
              "tools, dashboards with sample data. No server-side code. Can remember things per browser "
              "with localStorage.",
              ("static/index.html",), True,
              "a Lambda function with a public URL that serves the page"),
    Blueprint("web-app",
              "A web page plus a small JSON API in Python, for anything that must save or share data "
              "between visitors or devices: todo lists, guestbooks, polls, leaderboards, URL shorteners, "
              "simple CRUD apps, or an API with no page.",
              ("api.py", "static/index.html"), True,
              "a Lambda function with a public URL that serves the page and its API"),
    Blueprint("scheduled-job",
              "Python code that runs on a schedule with no user interface: periodic clean-ups, reports, "
              "reminders, counters.",
              ("job.py",), False,
              "a Lambda function run on a schedule by Amazon EventBridge"),
)}


def resource_name(app_id: str) -> str:
    return f"{RESOURCE_PREFIX}{app_id}"


def render_template(blueprint: str, app_id: str, title: str, uses_store: bool,
                    schedule: str = DEFAULT_SCHEDULE) -> str:
    """The complete CloudFormation template for one app."""
    bp = BLUEPRINTS[blueprint]
    name = resource_name(app_id)
    safe_title = re.sub(r"[^\w .,()-]", "", title or app_id)[:120]
    variables = [f"          APP_ID: {app_id}"]
    if uses_store:
        variables.append("          TABLE_NAME: !Ref Table")
    lines: List[str] = [
        'AWSTemplateFormatVersion: "2010-09-09"',
        f'Description: "CloudOps generated app: {safe_title} ({blueprint} blueprint)"',
        "Parameters:",
        "  ArtifactBucket: {Type: String}",
        "  ArtifactKey: {Type: String}",
        "Resources:",
        "  Function:",
        "    Type: AWS::Lambda::Function",
        "    Properties:",
        f"      FunctionName: {name}",
        "      Description: Generated by CloudOps. Entry point handler.py is platform code.",
        "      Runtime: python3.12",
        "      Handler: handler.handler",
        "      Architectures: [arm64]",
        f"      MemorySize: {256 if bp.has_url else 512}",
        f"      Timeout: {15 if bp.has_url else 300}",
        # A shared, pre-created role: logs plus DynamoDB tables named cloudops-gen-* only.
        f'      Role: !Sub "arn:${{AWS::Partition}}:iam::${{AWS::AccountId}}:role/{EXECUTION_ROLE_NAME}"',
        "      Code: {S3Bucket: !Ref ArtifactBucket, S3Key: !Ref ArtifactKey}",
        "      Environment:",
        "        Variables:",
        *variables,
    ]
    if bp.has_url:
        lines += [
            "  Url:",
            "    Type: AWS::Lambda::Url",
            "    Properties: {TargetFunctionArn: !GetAtt Function.Arn, AuthType: NONE}",
            # A public function URL needs both permissions.
            "  UrlPermission:",
            "    Type: AWS::Lambda::Permission",
            "    Properties:",
            "      FunctionName: !Ref Function",
            "      Action: lambda:InvokeFunctionUrl",
            '      Principal: "*"',
            "      FunctionUrlAuthType: NONE",
            "  UrlInvokePermission:",
            "    Type: AWS::Lambda::Permission",
            "    Properties:",
            "      FunctionName: !Ref Function",
            "      Action: lambda:InvokeFunction",
            '      Principal: "*"',
            "      InvokedViaFunctionUrl: true",
        ]
    else:
        lines += [
            "  Schedule:",
            "    Type: AWS::Events::Rule",
            "    Properties:",
            f"      Name: {name}",
            f'      ScheduleExpression: "{schedule if SCHEDULE_RE.match(schedule or "") else DEFAULT_SCHEDULE}"',
            "      State: ENABLED",
            "      Targets: [{Arn: !GetAtt Function.Arn, Id: job}]",
            "  SchedulePermission:",
            "    Type: AWS::Lambda::Permission",
            "    Properties:",
            "      FunctionName: !Ref Function",
            "      Action: lambda:InvokeFunction",
            "      Principal: events.amazonaws.com",
            "      SourceArn: !GetAtt Schedule.Arn",
        ]
    if uses_store:
        lines += [
            "  Table:",
            "    Type: AWS::DynamoDB::Table",
            "    Properties:",
            f"      TableName: {name}",
            "      BillingMode: PAY_PER_REQUEST",
            "      AttributeDefinitions:",
            "        - {AttributeName: pk, AttributeType: S}",
            "        - {AttributeName: sk, AttributeType: S}",
            "      KeySchema:",
            "        - {AttributeName: pk, KeyType: HASH}",
            "        - {AttributeName: sk, KeyType: RANGE}",
            "      SSESpecification: {SSEEnabled: true}",
        ]
    lines += ["Outputs:"]
    if bp.has_url:
        lines += ["  AppUrl: {Value: !GetAtt Url.FunctionUrl}"]
    lines += ["  FunctionName: {Value: !Ref Function}"]
    if uses_store:
        lines += ["  TableName: {Value: !Ref Table}"]
    return "\n".join(lines) + "\n"


def what_it_creates(blueprint: str, uses_store: bool) -> str:
    text = BLUEPRINTS[blueprint].creates
    return text + (" and a DynamoDB table for its data" if uses_store else "")
